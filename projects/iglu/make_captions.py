#!/usr/bin/env python3
"""captions.txt + audio/vo.words.json -> src/captions.js (CAPTIONS, DURATION) and iglu.srt

Each line of captions.txt is one caption; its words are matched in order to the word timings.
A caption starts at its first word and ends at the next caption's first word
(or 0.35 s after its last word when a pause follows)."""
import json, re, sys

words = json.load(open('audio/vo.words.json'))
lines = [l.strip() for l in open('captions.txt', encoding='utf-8') if l.strip() and not l.startswith('#')]
plain = lambda s: re.sub(r'[*^]', '', s)
norm = lambda w: re.sub(r'[^\w]', '', w.lower())
caps, i = [], 0
for line in lines:
    ws = plain(line).split()
    for k, w in enumerate(ws):
        if norm(words[i + k]['w']) != norm(w):
            sys.exit(f'mismatch at "{line}": {words[i + k]["w"]} vs {w}')
    caps.append({'text': line, 's': words[i]['s'], 'e': words[i + len(ws) - 1]['e'], 'last': words[i + len(ws) - 1]})
    i += len(ws)
assert i == len(words), (i, len(words))
out = []
for k, c in enumerate(caps):
    start = max(0.0, c['s'] - 0.06)
    if k + 1 < len(caps):
        nxt = caps[k + 1]['s'] - 0.06
        end = nxt if nxt - c['last']['s'] < 0.9 else min(nxt, c['last']['s'] + 0.75)
    else:
        end = c['e'] + 0.4
    out.append((start, c['text'], end))
dur = round(words[-1]['e'] + 0.45, 2)
with open('src/captions.js', 'w', encoding='utf-8') as f:
    f.write('// generated by make_captions.py from captions.txt + audio/vo.words.json\n')
    f.write(f'export const DURATION = {dur};\n')
    f.write('// [start, text, end]\nexport const CAPTIONS = [\n')
    for s, t, e in out:
        f.write(f"  [{s:.2f}, {json.dumps(t, ensure_ascii=False)}, {e:.2f}],\n")
    f.write('];\n')
def ts(x):
    ms = int(round(x * 1000)); h, ms = divmod(ms, 3600000); m, ms = divmod(ms, 60000); s, ms = divmod(ms, 1000)
    return f'{h:02d}:{m:02d}:{s:02d},{ms:03d}'
with open('iglu.srt', 'w', encoding='utf-8') as f:
    for n, (s, t, e) in enumerate(out, 1):
        f.write(f'{n}\n{ts(s)} --> {ts(e)}\n{plain(t)}\n\n')
print(f'{len(out)} captions, duration {dur}')
for s, t, e in out: print(f'{s:6.2f} {e:6.2f}  {t}')
